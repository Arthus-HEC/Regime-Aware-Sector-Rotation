# Main
# ============================================================

def main() -> None:
    """
    Run bootstrap significance analysis.
    """
    print("=" * 80)
    print("Bootstrap significance analysis")
    print("=" * 80)

    returns = load_comparison_returns()

    print()
    print("Return matrix loaded:")
    print(returns.tail())
    print()
    print(f"Shape: {returns.shape}")
    print(f"Date range: {returns.index.min().date()} to {returns.index.max().date()}")

    summary, distributions = run_bootstrap_significance_analysis(
        returns=returns,
    )

    DATA_DIR.mkdir(parents=True, exist_ok=True)

    summary.to_csv(BOOTSTRAP_SUMMARY_PATH, index=False)
    distributions.to_csv(BOOTSTRAP_DISTRIBUTIONS_PATH, index=False)

    print()
    print("Bootstrap summary:")
    display_columns = [
        "benchmark",
        "metric",
        "observed_difference",
        "ci_2_5",
        "ci_97_5",
        "probability_favorable",
        "p_two_sided_zero",
        "interpretation",
    ]
    print(
        format_summary_for_display(summary[display_columns])
        .to_string(index=False)
    )

    print()
    print("Saved outputs:")
    print(f"- {BOOTSTRAP_SUMMARY_PATH}")
    print(f"- {BOOTSTRAP_DISTRIBUTIONS_PATH}")

    print()
    print("Done.")


if __name__ == "__main__":
    main()